import argparse
import json
import os
import random
from typing import Any, Optional

try:
  from datasets import load_dataset
except ModuleNotFoundError as exc:
  load_dataset = None
  _DATASETS_IMPORT_ERROR = exc
else:
  _DATASETS_IMPORT_ERROR = None


DATASET_ID = "HuggingFaceH4/Multilingual-Thinking"
DEFAULT_OUTPUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "data",
    "reasonif_multilingual_thinking_dataset.jsonl",
)
TARGET_INSTRUCTION_IDS = [
    "reasonif:language:reasoning_language",
    "reasonif:length_constraint_checkers:number_words",
    "reasonif:change_case:english_capital",
    "reasonif:startend:end_checker",
    "reasonif:detectable_format:json_format",
    "reasonif:punctuation:no_comma",
]
MIN_WORD_LIMIT = 38
MAX_WORD_LIMIT = 860
LANGUAGE_CODES = {
    "en": "English",
    "es": "Spanish",
    "pt": "Portuguese",
    "ar": "Arabic",
    "hi": "Hindi",
    "fr": "French",
    "ru": "Russian",
    "de": "German",
    "ja": "Japanese",
    "zh": "Chinese",
    "it": "Italian",
    "bn": "Bengali",
    "uk": "Ukrainian",
    "th": "Thai",
    "ur": "Urdu",
    "ta": "Tamil",
    "te": "Telugu",
    "bg": "Bulgarian",
    "ko": "Korean",
    "pl": "Polish",
    "he": "Hebrew",
    "fa": "Persian",
    "vi": "Vietnamese",
    "ne": "Nepali",
    "sw": "Swahili",
    "kn": "Kannada",
    "mr": "Marathi",
    "gu": "Gujarati",
    "pa": "Punjabi",
    "ml": "Malayalam",
    "fi": "Finnish",
}
REASONIF_ENDING_OPTIONS = (
    "THIS THOUGHT PROCESS WAS GENERATED BY AI",
    "THIS REASONING WAS PRODUCED BY AI",
    "THIS ANALYSIS WAS CREATED BY AI",
    "THIS LOGIC WAS GENERATED THROUGH AI",
    "THIS EXPLANATION IS AI-GENERATED",
    "THIS ARGUMENT WAS CONSTRUCTED BY AI",
)

PROMPT_TEMPLATE = (
    "{developer}\n\n"
    "{user}\n\n"
    "<thinking guidelines>\n"
    "{constraint_text}\n"
    "</thinking guidelines>"
)


def _get_required_text(
    example: dict[str, Any],
    key: str,
    row_number: int,
) -> str:
  value = example.get(key)
  if not isinstance(value, str) or not value.strip():
    raise ValueError(f"Row {row_number}: missing non-empty {key!r}.")
  return value.strip()


def _build_instruction(
    inst_id: str,
    rng: random.Random,
) -> tuple[str, dict[str, Any]]:
  if inst_id == "reasonif:language:reasoning_language":
    language = rng.choice(tuple(LANGUAGE_CODES))
    return (
        "When reasoning, use only "
        f"{LANGUAGE_CODES[language].capitalize()} language, no other "
        "language is allowed.",
        {"language": language},
    )

  if inst_id == "reasonif:length_constraint_checkers:number_words":
    num_words = rng.randint(MIN_WORD_LIMIT, MAX_WORD_LIMIT)
    return (
        f"When reasoning, use less than {num_words} words.",
        {"num_words": num_words},
    )

  if inst_id == "reasonif:change_case:english_capital":
    return "When reasoning, use only capital letters.", {}

  if inst_id == "reasonif:startend:end_checker":
    end_phrase = rng.choice(REASONIF_ENDING_OPTIONS)
    return (
        'When reasoning, put this exact phrase '
        f'"{end_phrase}" in the end of reasoning. No other reasoning words '
        "should follow this phrase.",
        {"end_phrase": end_phrase},
    )

  if inst_id == "reasonif:detectable_format:json_format":
    return (
        "When reasoning, follow JSON format. "
        "You can use markdown ticks such as ```.",
        {},
    )

  if inst_id == "reasonif:punctuation:no_comma":
    return "When reasoning, refrain from the use of any commas.", {}

  raise ValueError(f"Unsupported instruction id: {inst_id}")


def generate_records(
    seed: int,
    split: str,
    limit: Optional[int],
    shuffle: bool,
) -> list[dict[str, Any]]:
  if load_dataset is None:
    raise ModuleNotFoundError(
        "The 'datasets' package is required to load "
        f"{DATASET_ID}. Install instruction_following_eval/requirements.txt."
    ) from _DATASETS_IMPORT_ERROR

  rng = random.Random(seed)
  dataset = list(load_dataset(DATASET_ID, split=split))
  if shuffle:
    rng.shuffle(dataset)
  if limit is not None:
    dataset = dataset[:limit]

  records = []
  for key, example in enumerate(dataset):
    developer = _get_required_text(example, "developer", key)
    user = _get_required_text(example, "user", key)
    inst_id = rng.choice(TARGET_INSTRUCTION_IDS)
    constraint_text, kwargs = _build_instruction(inst_id, rng)
    record = {
        "key": key,
        "prompt": PROMPT_TEMPLATE.format(
            developer=developer,
            user=user,
            constraint_text=constraint_text,
        ),
        "instruction_id_list": [inst_id],
        "kwargs": [kwargs],
        "source": DATASET_ID,
    }
    final = example.get("final")
    if isinstance(final, str):
      record["answer"] = final
    reasoning_language = example.get("reasoning_language")
    if isinstance(reasoning_language, str):
      record["reasoning_language"] = reasoning_language
    records.append(record)

  return records


def main() -> None:
  parser = argparse.ArgumentParser(
      description=(
          "Create IF-Eval style JSONL tasks from "
          "HuggingFaceH4/Multilingual-Thinking using developer + user prompts "
          "and sampled ReasonIF reasoning instructions."
      )
  )
  parser.add_argument(
      "--output",
      type=str,
      default=DEFAULT_OUTPUT,
      help="Output JSONL file path.",
  )
  parser.add_argument(
      "--seed",
      type=int,
      default=42,
      help="Random seed for shuffling and word-limit sampling.",
  )
  parser.add_argument(
      "--split",
      type=str,
      default="train",
      help="Hugging Face dataset split to load.",
  )
  parser.add_argument(
      "--limit",
      type=int,
      default=None,
      help="Optional maximum number of examples to write.",
  )
  parser.add_argument(
      "--shuffle",
      action=argparse.BooleanOptionalAction,
      default=False,
      help="Shuffle dataset rows before applying --limit.",
  )
  args = parser.parse_args()

  records = generate_records(
      seed=args.seed,
      split=args.split,
      limit=args.limit,
      shuffle=args.shuffle,
  )

  with open(args.output, "w", encoding="utf-8") as output_file:
    for row in records:
      output_file.write(json.dumps(row, ensure_ascii=False) + "\n")

  print(f"Wrote {len(records)} samples to {args.output}")


if __name__ == "__main__":
  main()
